using System.Collections.Generic;
using System.Linq;
using Cysharp.Threading.Tasks;
using mumu;
using UnityEngine;

public class InGameMap
{
    private Block block = null;
    private GameObject mapRoot = null;

    public async UniTask InitAsync(GameObject _mapRoot)
    {
        mapRoot = _mapRoot;
        block = await ResourceManager.Instance.LoadAsync<Block>(ResourceManager.GetInGamePrefabPath("block"));
        block.gameObject.SetActive(false); // Deactivate original block
                                           //generateMap(6, 4, eGameMode.Extreme);

        mapData = loadMap();
        GenerateBlock(mapData);
        ApplyMap(mapData);
    }
    private const int blockSize = 60;
    private const int blockSpacing = 0;

    private Block[,] blockArray;
    private MapData mapData;

    List<Block> sortedBlocks = new List<Block>();

    private void GenerateBlock(MapData mapData)
    {
        int _xCount = mapData.width;
        int _yCount = mapData.height;

        blockArray = new Block[_xCount, _yCount];

        float tileWidth = blockSize + blockSpacing;
        float tileHeight = tileWidth * 0.5f;
        float halfTileWidth = tileWidth * 0.5f;
        float halfTileHeight = tileHeight * 0.5f;

        float centerOffsetX = (_xCount - _yCount) * halfTileWidth * 0.5f;
        float centerOffsetY = ((_xCount + _yCount - 2) * halfTileHeight) * 0.5f;

        block.gameObject.SetActive(false);

        for (int x = 0; x < _xCount; x++)
        {
            for (int y = 0; y < _yCount; y++)
            {
                // 🔥 Flip Y for correct visual layout
                int flippedY = (_yCount - 1) - y;

                Block newBlock = GameObject.Instantiate(block, mapRoot.transform);
                RectTransform rect = newBlock.GetComponent<RectTransform>();

                rect.anchorMin = new Vector2(0.5f, 0.5f);
                rect.anchorMax = new Vector2(0.5f, 0.5f);
                rect.pivot = new Vector2(0.5f, 0.5f);
                rect.localScale = Vector3.one;
                rect.localRotation = Quaternion.identity;
                rect.sizeDelta = new Vector2(blockSize, blockSize);

                // Isometric position
                float posX = (x - flippedY) * halfTileWidth - centerOffsetX;
                float posY = (x + flippedY) * halfTileHeight - centerOffsetY;

                rect.anchoredPosition = new Vector2(posX, posY);

                newBlock.gameObject.SetActive(true);

                // 🔥 IMPORTANT: use flippedY for sorting too
                newBlock.SetOrder(x, flippedY, _xCount, _yCount);
                blockArray[x, y] = newBlock;
                sortedBlocks.Add(blockArray[x, y]);
            }
        }
        sortedBlocks.OrderByDescending(b => b.SortIndex).ToList().ForEach(b => b.transform.SetAsFirstSibling());
    }

    // Generated by Claude Code
    private void generateMap(int _xCount, int _yCount, eGameMode _gameMode)
    {
        // Create MapData ScriptableObject
        mapData = ScriptableObject.CreateInstance<MapData>();
        mapData.Initialize(_xCount, _yCount);

        // Calculate middle row index
        int middleY = _yCount / 2;

        for (int x = 0; x < _xCount; x++)
        {
            for (int y = 0; y < _yCount; y++)
            {
                eBlockType blockType;

                // Left side (x == 0)
                if (x == 0)
                {
                    if (y == middleY)
                    {
                        // Start block at left middle
                        blockType = eBlockType.Start;
                    }
                    else
                    {
                        // Other left side blocks are empty
                        blockType = eBlockType.Empty;
                    }
                }
                // Right side (x == xCount - 1)
                else if (x == _xCount - 1)
                {
                    if (y == middleY)
                    {
                        // Goal block at right middle
                        blockType = eBlockType.Goal;
                    }
                    else
                    {
                        // Other right side blocks are empty
                        blockType = eBlockType.Empty;
                    }
                }
                // Middle blocks are walkable
                else
                {
                    blockType = eBlockType.Walkable;
                }

                // Set block type to MapData only
                mapData.SetBlockType(x, y, blockType);
            }
        }

        // Calculate path count based on game mode
        int minPath = _xCount - 2; // Straight line distance
        int maxPath = (_xCount - 2) * (_yCount - 2);
        int pathCount = getPathCountByMode(_gameMode, minPath, maxPath);

        mapData = generateWalkPath(mapData, pathCount);
        // Save asset
        string path = "Assets/mumu/Resources/MapData/mapdata.asset";
        UnityEditor.AssetDatabase.CreateAsset(mapData, path);
        UnityEditor.AssetDatabase.SaveAssets();
        Debug.Log($"MapData saved to {path} with difficulty {_gameMode}, pathCount: {pathCount}");
    }

    // Generated by Claude Code
    private int getPathCountByMode(eGameMode _mode, int _minPath, int _maxPath)
    {
        float totalRange = _maxPath - _minPath;

        switch (_mode)
        {
            case eGameMode.Easy:
                // 10-20% of total range
                int easyMin = _minPath;
                int easyMax = _minPath + Mathf.CeilToInt(totalRange * 0.15f);
                return UnityEngine.Random.Range(easyMin, easyMax + 1);

            case eGameMode.Normal:
                // 20-40% of total range
                int normalMin = _minPath + Mathf.CeilToInt(totalRange * 0.15f);
                int normalMax = _minPath + Mathf.CeilToInt(totalRange * 0.35f);
                return UnityEngine.Random.Range(normalMin, normalMax + 1);

            case eGameMode.Hard:
                // 40-60% of total range
                int hardMin = _minPath + Mathf.CeilToInt(totalRange * 0.35f);
                int hardMax = _minPath + Mathf.CeilToInt(totalRange * 0.55f);
                return UnityEngine.Random.Range(hardMin, hardMax + 1);

            case eGameMode.VeryHard:
                // 60-80% of total range
                int veryHardMin = _minPath + Mathf.CeilToInt(totalRange * 0.55f);
                int veryHardMax = _minPath + Mathf.CeilToInt(totalRange * 0.75f);
                return UnityEngine.Random.Range(veryHardMin, veryHardMax + 1);

            case eGameMode.Extreme:
                // 80-95% of total range
                int extremeMin = _minPath + Mathf.CeilToInt(totalRange * 0.75f);
                int extremeMax = _minPath + Mathf.CeilToInt(totalRange * 0.95f);
                return UnityEngine.Random.Range(extremeMin, extremeMax + 1);

            default:
                return _minPath;
        }
    }

    // Generated by Claude Code
    private MapData generateWalkPath(MapData mapData, int _pathCount)
    {
        // Find start and goal positions
        int startX = -1, startY = -1;
        int goalX = -1, goalY = -1;

        for (int x = 0; x < mapData.width; x++)
        {
            for (int y = 0; y < mapData.height; y++)
            {
                eBlockType blockType = mapData.GetBlockType(x, y);
                if (blockType == eBlockType.Start)
                {
                    startX = x;
                    startY = y;
                }
                else if (blockType == eBlockType.Goal)
                {
                    goalX = x;
                    goalY = y;
                }
            }
        }

        if (startX == -1 || goalX == -1)
        {
            Debug.LogError("Start or Goal not found in mapData");
            return mapData;
        }

        // Calculate minimum path length (straight line)
        int minPathLength = goalX - startX - 1;

        // If pathCount is minimum or less, create straight line
        if (_pathCount <= minPathLength)
        {
            for (int x = startX + 1; x < goalX; x++)
            {
                mapData.AddBlockSubType(x, startY, eBlockSubType.Waypoint);
            }
            Debug.Log($"Generated straight path with {minPathLength} blocks");
            return mapData;
        }

        // Generate complex winding path with proper backtracking
        HashSet<(int, int)> visitedBlocks = new HashSet<(int, int)>();
        List<(int, int)> path = new List<(int, int)>();

        int currentX = startX;
        int currentY = startY;
        visitedBlocks.Add((currentX, currentY));

        int targetSteps = Mathf.Min(_pathCount, (goalX - startX - 1) * (mapData.height - 2));

        while (path.Count < targetSteps)
        {
            int distToGoal = (goalX - currentX - 1) + Mathf.Abs(goalY - currentY);
            int remainingSteps = targetSteps - path.Count;

            List<(int, int)> validMoves = new List<(int, int)>();

            // Get all valid moves
            // Right
            if (currentX + 1 < goalX && !visitedBlocks.Contains((currentX + 1, currentY)))
            {
                validMoves.Add((currentX + 1, currentY));
            }

            // Left (backward) - allow if enough steps remain
            if (currentX - 1 > startX && remainingSteps > distToGoal + 3 && !visitedBlocks.Contains((currentX - 1, currentY)))
            {
                validMoves.Add((currentX - 1, currentY));
            }

            // Up
            if (currentY + 1 < mapData.height - 1 &&
                mapData.GetBlockType(currentX, currentY + 1) == eBlockType.Walkable &&
                !visitedBlocks.Contains((currentX, currentY + 1)))
            {
                validMoves.Add((currentX, currentY + 1));
            }

            // Down
            if (currentY - 1 >= 1 &&
                mapData.GetBlockType(currentX, currentY - 1) == eBlockType.Walkable &&
                !visitedBlocks.Contains((currentX, currentY - 1)))
            {
                validMoves.Add((currentX, currentY - 1));
            }

            // If stuck, backtrack
            if (validMoves.Count == 0)
            {
                // Backtrack: remove last position from path and visited
                if (path.Count > 0)
                {
                    var backtrackPos = path[path.Count - 1];
                    path.RemoveAt(path.Count - 1);
                    visitedBlocks.Remove(backtrackPos);

                    // Update current position
                    if (path.Count > 0)
                    {
                        currentX = path[path.Count - 1].Item1;
                        currentY = path[path.Count - 1].Item2;
                    }
                    else
                    {
                        currentX = startX;
                        currentY = startY;
                    }
                    continue; // Try again from backtracked position
                }
                else
                {
                    // Can't backtrack anymore
                    break;
                }
            }

            // Apply movement preferences based on remaining steps
            if (remainingSteps > distToGoal + 10)
            {
                // Far from goal: strongly prefer complex moves (vertical/backward)
                if (UnityEngine.Random.value < 0.85f)
                {
                    var complexMoves = validMoves.Where(m => m.Item2 != currentY || m.Item1 < currentX).ToList();
                    if (complexMoves.Count > 0) validMoves = complexMoves;
                }
            }
            else if (remainingSteps < distToGoal + 2)
            {
                // Close to goal: prioritize moves toward goal
                var goalMoves = validMoves.Where(m => m.Item1 > currentX || Mathf.Abs(m.Item2 - goalY) < Mathf.Abs(currentY - goalY)).ToList();
                if (goalMoves.Count > 0) validMoves = goalMoves;
            }

            // Choose move
            var nextMove = validMoves[UnityEngine.Random.Range(0, validMoves.Count)];
            currentX = nextMove.Item1;
            currentY = nextMove.Item2;
            path.Add(nextMove);
            visitedBlocks.Add(nextMove);

            // Check if reached near goal
            if (path.Count >= targetSteps - 5 && currentX >= goalX - 2)
            {
                break;
            }
        }

        // Final approach to goal - MUST reach goal
        // First move horizontally as much as possible
        while (currentX < goalX - 1)
        {
            if (!visitedBlocks.Contains((currentX + 1, currentY)))
            {
                currentX++;
                path.Add((currentX, currentY));
                visitedBlocks.Add((currentX, currentY));
            }
            else
            {
                // Try to go around the obstacle
                bool moved = false;

                // Try up
                if (currentY + 1 < mapData.height - 1 && !visitedBlocks.Contains((currentX, currentY + 1)))
                {
                    currentY++;
                    path.Add((currentX, currentY));
                    visitedBlocks.Add((currentX, currentY));
                    moved = true;
                }
                // Try down
                else if (currentY - 1 >= 1 && !visitedBlocks.Contains((currentX, currentY - 1)))
                {
                    currentY--;
                    path.Add((currentX, currentY));
                    visitedBlocks.Add((currentX, currentY));
                    moved = true;
                }

                if (!moved)
                {
                    break;
                }
            }
        }

        // Then align vertically to goal
        while (currentY != goalY)
        {
            int nextY = currentY + (goalY > currentY ? 1 : -1);
            if (!visitedBlocks.Contains((currentX, nextY)) &&
                mapData.GetBlockType(currentX, nextY) == eBlockType.Walkable)
            {
                currentY = nextY;
                path.Add((currentX, currentY));
                visitedBlocks.Add((currentX, currentY));
            }
            else
            {
                // Try going around
                if (currentX + 1 < goalX && !visitedBlocks.Contains((currentX + 1, currentY)))
                {
                    currentX++;
                    path.Add((currentX, currentY));
                    visitedBlocks.Add((currentX, currentY));
                }
                else if (currentX - 1 > startX && !visitedBlocks.Contains((currentX - 1, currentY)))
                {
                    currentX--;
                    path.Add((currentX, currentY));
                    visitedBlocks.Add((currentX, currentY));
                }
                else
                {
                    break;
                }
            }
        }

        // Final push to goal X position
        while (currentX < goalX - 1)
        {
            if (!visitedBlocks.Contains((currentX + 1, currentY)))
            {
                currentX++;
                path.Add((currentX, currentY));
                visitedBlocks.Add((currentX, currentY));
            }
            else
            {
                break;
            }
        }

        // Add waypoint subtype to all path blocks
        foreach (var (x, y) in path)
        {
            if (mapData.GetBlockType(x, y) == eBlockType.Walkable)
            {
                mapData.AddBlockSubType(x, y, eBlockSubType.Waypoint);
            }
        }

        Debug.Log($"Generated complex winding path with {path.Count} blocks (target: {_pathCount}) from ({startX},{startY}) to ({goalX},{goalY})");
        return mapData;
    }

    // Generated by Claude Code
    private MapData loadMap()
    {
        // Load MapData from Resources
        var mapData = ResourceManager.Instance.Load<MapData>(ResourceManager.MapDataPath);

        if (mapData == null)
        {
            Debug.LogError("Failed to load mapdata from Resources");
            return null;
        }
        return mapData;
    }

    private void ApplyMap(MapData mapData)
    {
        // Apply loaded data to block array
        for (int x = 0; x < mapData.width; x++)
        {
            for (int y = 0; y < mapData.height; y++)
            {
                if (blockArray != null && x < blockArray.GetLength(0) && y < blockArray.GetLength(1))
                {
                    Block currentBlock = blockArray[x, y];

                    // Apply block type
                    eBlockType blockType = mapData.GetBlockType(x, y);
                    currentBlock.SetBlockType(blockType);

                    // Apply block subtypes
                    List<eBlockSubType> subTypes = mapData.GetBlockSubTypes(x, y);
                    foreach (var subType in subTypes)
                    {
                        currentBlock.AddSubType(subType);
                    }
                    currentBlock.SetDubugText();
                }
            }
        }
    }
